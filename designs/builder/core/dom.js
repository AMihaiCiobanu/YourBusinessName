// Unsplash serves AVIF/WebP with auto=format, cropped to the size asked. `p` is an entry from
// content/photos.js; alt text comes in the page language.
export function photoUrl(p, w, hgt, q = 62) {
  return `https://images.unsplash.com/${p.id}?auto=format&fit=crop&crop=entropy&w=${Math.round(w)}&h=${Math.round(hgt)}&q=${q}`;
}

export function photo(p, { w = 800, h: hgt = 600, sizes = '100vw', alt = '', eager = false, className = '', priority = false } = {}) {
  if (!p) return h('span', { class: `ph-missing ${className}`, 'aria-hidden': 'true' });
  const widths = [0.5, 1, 1.5].map(f => Math.round(w * f));
  const img = h('img', {
    class: className || null,
    src: photoUrl(p, w, hgt),
    srcset: widths.map(x => `${photoUrl(p, x, (x * hgt) / w)} ${x}w`).join(', '),
    sizes,
    width: w,
    height: hgt,
    alt,
    loading: eager ? 'eager' : 'lazy',
    decoding: 'async',
    fetchpriority: priority ? 'high' : null,
    draggable: 'false'
  });
  return img;
}

// Text for screen readers next to decorative split text.
export function srOnly(text) {
  return h('span', { class: 'sr-only', text });
}

export function clamp(v, min, max) { return Math.min(max, Math.max(min, v)); }
